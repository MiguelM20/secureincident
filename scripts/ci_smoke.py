"""Noninteractive integration checks against a fresh Docker Compose deployment.

Credentials are generated by Jenkins for the disposable CI environment. This
script never prints passwords, JWTs, or response bodies.
"""

import json
import os
from urllib.error import HTTPError
from urllib.request import Request, urlopen

BASE = os.environ.get("SECUREINCIDENT_SMOKE_URL", "http://127.0.0.1:18080").rstrip("/")


def call(method: str, path: str, *, body=None, token=None):
    headers = {"Content-Type": "application/json"}
    if token:
        headers["Authorization"] = "Bearer " + token
    req = Request(
        BASE + path,
        data=json.dumps(body).encode("utf-8") if body is not None else None,
        headers=headers,
        method=method,
    )
    try:
        with urlopen(req, timeout=15) as resp:
            return resp.status, json.load(resp)
    except HTTPError as exc:
        return exc.code, None


def main():
    password = os.environ.get("SECUREINCIDENT_SMOKE_PASSWORD")
    if not password:
        raise SystemExit("Missing disposable CI credential")

    status, auth = call("POST", "/auth/login", body={"username": "alice", "password": password})
    if status != 200 or not auth or "access_token" not in auth:
        raise SystemExit(f"CI login failed: HTTP {status}")
    token = auth["access_token"]

    checks = [
        ("Own incident readable", *call("GET", "/incidents/101", token=token), 200),
        ("Other user's incident denied", *call("GET", "/incidents/102", token=token), 404),
        ("Admin action denied", *call("GET", "/admin/overview", token=token), 403),
    ]
    status, report = call("POST", "/incidents/101/reports", body={}, token=token)
    checks.append(("Generate own report", status, report, 201))
    checks.append(("Unsafe report filename denied", *call(
        "POST", "/incidents/101/reports", body={"filename": "../outside.txt"}, token=token
    ), 422))
    if status == 201 and report and "id" in report:
        checks.append(("Read saved report", *call(
            "GET", f"/incidents/101/reports/{report['id']}", token=token
        ), 200))
    else:
        checks.append(("Read saved report", 0, None, 200))

    bad = False
    for label, actual, _payload, expected in checks:
        print(f"{label}: HTTP {actual} (expected {expected})")
        bad |= actual != expected
    if bad:
        raise SystemExit("Docker integration security gate FAILED")
    print("Docker integration security gate PASSED")


if __name__ == "__main__":
    main()
